// The timing table in docs/animation.md, measured: for every style's string
// and special, the sim's hit frame and length next to the frame the body
// actually reaches its contact pose on (the first frame the striking point is
// within 1 cm of where the clip's contact pose puts it, relative to the pelvis) and the frame the
// striking point is fastest. Contact must land on the hit frame and the speed
// peak within a frame of it. Run with UPDATE_DOCS=1 to rewrite the table.
import { describe, expect, it } from "vitest";
import fs from "node:fs";
import * as THREE from "three";
import { applyPose, buildBody, targetPose, type Body } from "../src/render/body";
import { animate, ankleOf } from "../src/render/animate";
import { clipFor, familyOf, type Clip } from "../src/render/motion";
import { STYLES } from "../src/sim/styles";
import { World } from "../src/sim/world";

const DT = 1 / 60;
const DOC = new URL("../docs/animation.md", import.meta.url);
const BEGIN = "<!-- timing table: generated by tests/timing.test.ts -->";
const END = "<!-- end of timing table -->";
const MOVES = ["jab1", "jab2", "jab3", "punchFin", "kick1", "kick2", "sweep"];

/** The striking point, in the pelvis's frame (or the world's, for its speed). */
function tip(b: Body, clip: Clip, world = false): THREE.Vector3 {
  b.root.updateMatrixWorld(true);
  const v = new THREE.Vector3();
  if (clip.point === "elbow") b.joints[clip.limb === "armR" ? "elbowR" : "elbowL"].getWorldPosition(v);
  else if (clip.point) b.limbs[clip.point === "shoulderR" ? "armR" : "armL"].getWorldPosition(v);
  else if (clip.limb === "legL" || clip.limb === "legR") ankleOf(b, clip.limb === "legL" ? "L" : "R", v);
  else b.joints[clip.limb === "armR" ? "elbowR" : "elbowL"].localToWorld(v.set(0, -0.3, 0));
  return world ? v : b.hips.worldToLocal(v);
}

interface Row {
  style: string;
  family: string;
  move: string;
  hit: number;
  len: number;
  contact: number;
  peak: number;
}

function measure(style: number, move: string): Row | null {
  const clip = clipFor(style, move);
  if (!clip || clip.limb === "body" || clip.limb === "head" || clip.limb === "both") return null;
  const w = new World({ seed: 3, styles: [style, 0], humans: [true, true] });
  const f = w.fighters[0];
  const b = buildBody(f);
  Object.assign(f, { state: "idle", t: 0, stop: 0 });
  for (let i = 0; i < 90; i++) animate(b, f, w, i * DT, DT);
  const m = w.eff(f, move);
  Object.assign(f, { state: "attack", move, chargeHeld: false, charge: 0, t: m.startup });
  // where the contact pose puts the striking point
  const ref = buildBody(f);
  applyPose(ref, targetPose(f, w, 0, ref.hurt).p, 0, true, DT, 0);
  const goal = tip(ref, clip);
  const gap: number[] = [];
  const speed: number[] = [];
  let prev = tip(b, clip, true);
  for (let t = 0; t <= m.startup + 4; t++) {
    f.t = t;
    animate(b, f, w, (90 + t) * DT, DT);
    gap.push(tip(b, clip).distanceTo(goal));
    const p = tip(b, clip, true);
    speed.push(p.distanceTo(prev) / DT);
    prev = p;
  }
  const from = Math.max(0, m.startup - 8);
  const argmin = (xs: number[]) => from + xs.slice(from).indexOf(Math.min(...xs.slice(from)));
  const argmax = (xs: number[]) => from + xs.slice(from).indexOf(Math.max(...xs.slice(from)));
  // the frame it arrives (a spin then holds the pose while the body turns), or its closest pass
  const arrive = gap.findIndex((g, t) => t >= from && g < 0.01);
  return { style: STYLES[style].style, family: familyOf(style), move, hit: m.startup, len: m.total, contact: arrive >= 0 ? arrive : argmin(gap), peak: argmax(speed) };
}

const sign = (n: number) => (n > 0 ? `+${n}` : `${n}`);

describe("the timing table", () => {
  const rows: Row[] = [];
  for (let s = 0; s < STYLES.length; s++) for (const move of [...MOVES, STYLES[s].special]) rows.push(...[measure(s, move)].filter((r): r is Row => !!r));

  it("every strike reaches its contact pose on the sim's hit frame, at full speed within a frame of it", () => {
    for (const r of rows) {
      const why = `${r.style} ${r.move}`;
      expect(r.contact - r.hit, why).toBe(0);
      expect(Math.abs(r.peak - r.hit), why).toBeLessThanOrEqual(1);
    }
  });

  it("docs/animation.md has the measured table", () => {
    const table = [
      BEGIN,
      "",
      "| Style | Family | Move | Sim hit | Sim length | Contact lands | Δ | Fastest | Δ |",
      "|---|---|---|---:|---:|---:|---:|---:|---:|",
      ...rows.map((r) => `| ${r.style} | ${r.family} | ${r.move} | ${r.hit} | ${r.len} | ${r.contact} | ${sign(r.contact - r.hit)} | ${r.peak} | ${sign(r.peak - r.hit)} |`),
      "",
      END,
    ].join("\n");
    const doc = fs.readFileSync(DOC, "utf8").replace(/\r\n/g, "\n");
    const at = doc.indexOf(BEGIN);
    const end = doc.indexOf(END);
    expect(at, "the table's markers").toBeGreaterThanOrEqual(0);
    const now = doc.slice(at, end + END.length);
    if (process.env.UPDATE_DOCS) fs.writeFileSync(DOC, doc.slice(0, at) + table + doc.slice(end + END.length));
    else expect(now, "the table is out of date: run UPDATE_DOCS=1 npx vitest run tests/timing.test.ts").toBe(table);
  });
});
